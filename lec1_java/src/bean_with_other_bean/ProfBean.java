package bean_with_other_bean;

public class ProfBean {

	private int proid;
	private String proname;
	private PersonBean pc;
	public int getProid() {
		return proid;
	}
	public void setProid(int proid) {
		this.proid = proid;
	}
	public String getProname() {
		return proname;
	}
	public void setProname(String proname) {
		this.proname = proname;
	}
	public PersonBean getPc() {
		return pc;
	}
	public void setPc(PersonBean pc) {
		this.pc = pc;
	}
	
	
}
